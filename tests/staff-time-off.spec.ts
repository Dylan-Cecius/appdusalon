import { test, expect } from '@playwright/test';
test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-10-13T10:00:00'));
  await page.goto('/tests/fixtures/standalone.html?view=agenda');
});
test('blocks, edits and releases a period with persistence without adding an appointment', async ({ page }) => {
  await page.getByRole('button', { name: 'Indisponibilités', exact: true }).click();
  const sheet = page.getByRole('dialog');
  await sheet.getByRole('button', { name: 'Bloquer un créneau', exact: true }).click();
  const form = sheet.getByRole('form', { name: 'Indisponibilité', exact: true });
  await form.getByLabel('Collaborateur', { exact: true }).selectOption('demo-staff-0');
  await form.getByLabel('Libellé').fill('Formation test');
  await form.getByLabel('Début', { exact: true }).fill('16:00');
  await form.getByLabel('Fin', { exact: true }).fill('17:00');
  await form.getByRole('button', { name: 'Enregistrer l’indisponibilité' }).click();
  const card = sheet.getByRole('article', { name: 'Indisponibilité Formation test' });
  await expect(card).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Indisponibilité : Formation test' })).toBeVisible();
  await page.getByRole('button', { name: 'Nouveau rendez-vous', exact: true }).click();
  await sheet.getByLabel('Nom du client fictif').fill('Client bloqué');
  await sheet.getByLabel('Heure', { exact: true }).fill('16:15');
  await sheet.getByRole('button', { name: 'Créer le rendez-vous' }).click();
  await expect(sheet.getByRole('alert')).toHaveText('Ce collaborateur est indisponible sur cette période.');
  await page.keyboard.press('Escape');
  await page.reload();
  await page.getByRole('button', { name: 'Indisponibilités', exact: true }).click();
  await card.getByRole('button', { name: 'Modifier', exact: true }).click();
  await form.getByLabel('Fin', { exact: true }).fill('18:00');
  await form.getByRole('button', { name: 'Enregistrer l’indisponibilité' }).click();
  await expect(card).toContainText('18:00');
  await card.getByRole('button', { name: 'Libérer le créneau' }).click();
  await expect(card).toBeHidden();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Indisponibilité : Formation test' })).toHaveCount(0);
});
test('rejects occupied periods and filters blocked periods out of waitlist suggestions', async ({ page }) => {
  await page.getByRole('button', { name: 'Indisponibilités', exact: true }).click();
  const sheet = page.getByRole('dialog');
  await sheet.getByRole('button', { name: 'Bloquer un créneau', exact: true }).click();
  const form = sheet.getByRole('form', { name: 'Indisponibilité', exact: true });
  await form.getByLabel('Libellé').fill('Congé test');
  await form.getByLabel('Collaborateur', { exact: true }).selectOption('demo-staff-0');
  await form.getByLabel('Journée entière').check();
  await form.getByRole('button', { name: 'Enregistrer l’indisponibilité' }).click();
  await expect(form.getByRole('alert')).toContainText('Un rendez-vous existe');
  await form.getByLabel('Journée entière').uncheck();
  await form.getByLabel('Début', { exact: true }).fill('16:00');
  await form.getByLabel('Fin', { exact: true }).fill('19:00');
  await form.getByRole('button', { name: 'Enregistrer l’indisponibilité' }).click();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: /Liste d’attente/ }).click();
  await sheet.getByRole('button', { name: 'Ajouter une demande', exact: true }).click();
  const requestForm = sheet.getByRole('form', { name: 'Ajouter une demande' });
  await requestForm.getByLabel('Nom du client', { exact: true }).fill('Absence Test');
  await requestForm.getByLabel('Téléphone', { exact: true }).fill('0000000042');
  await requestForm.getByLabel('Collaborateur souhaité').selectOption('demo-staff-0');
  await requestForm.getByLabel('Disponible dès').fill('16:00');
  await requestForm.getByLabel('Jusqu’à', { exact: true }).fill('19:00');
  await requestForm.getByRole('button', { name: 'Ajouter la demande', exact: true }).click();
  const request = sheet.getByRole('article', { name: 'Demande de Absence Test' });
  await request.getByRole('button', { name: 'Trouver un créneau' }).click();
  await expect(request.getByText(/Aucun créneau adapté/)).toBeVisible();
});
